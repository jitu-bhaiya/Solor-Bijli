import { useState } from 'react'
import { FileText, Download, Copy } from 'lucide-react'
import { useApp } from '../context/AppContext'
import { buildInsights, totalSavings, reportText } from '../utils/insights'
import { download, money } from '../utils/format'
import { PageHeader, Badge, Empty } from '../components/common/UI'
export default function EnergyInsights() {
  const { readings, appliances, settings, notify } = useApp()
  const [report, setReport] = useState('')
  const ins = buildInsights(readings, appliances, settings)
  const copy = async () => { try { await navigator.clipboard.writeText(report); notify('Report copied') } catch { notify('Copy blocked by browser', 'err') } }
  return (
    <>
      <PageHeader title="Energy insights" sub="Generated by a transparent rule-based engine on demo data. No external AI is used.">
        <button className="btn" onClick={() => setReport(reportText(readings, appliances, settings))}><FileText size={16} />Generate report</button>
      </PageHeader>
      <p className="mb-4 rounded-lg bg-emerald-50 p-4 text-sm text-emerald-900 dark:bg-emerald-950 dark:text-emerald-200">Potential savings: <b>{money(totalSavings(ins), settings.currency)}/month</b> if you act on all suggestions below.</p>
      {report && <section className="card mb-4"><pre className="whitespace-pre-wrap text-sm">{report}</pre>
        <div className="mt-3 flex gap-2"><button className="btn btn-ghost" onClick={() => { download(report, 'solor-bijli-report.txt'); notify('Report downloaded') }}><Download size={16} />Download</button><button className="btn btn-ghost" onClick={copy}><Copy size={16} />Copy</button></div></section>}
      {ins.length ? <div className="grid gap-4 md:grid-cols-2">{ins.map((x) => (
        <article key={x.id} className="card"><div className="flex items-start justify-between gap-2"><h2 className="font-medium">{x.title}</h2><Badge level={x.priority} /></div>
          {x.savings > 0 && <p className="mt-1 text-sm font-medium text-emerald-600">Save about {money(x.savings, settings.currency)}/month</p>}
          <ul className="mt-3 list-disc space-y-1 pl-5 text-sm">{x.steps.map((s) => <li key={s}>{s}</li>)}</ul>
          <p className="muted mt-3 text-xs">{x.basis}</p></article>))}</div>
        : <Empty title="No insights yet" text="Add appliances and readings to generate suggestions." />}
    </>
  )
}
